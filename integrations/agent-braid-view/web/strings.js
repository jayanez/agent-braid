const TAG = /^([A-Za-z]{2,3})(?:[-_.@].*)?$/;

// "es", "es-MX", "es_ES.UTF-8" and "ES" are Spanish; a tag that is not supported (or "C", "POSIX") is null.
export function normalizeTag(tag) {
  if (typeof tag !== "string") return null;
  const match = TAG.exec(tag.trim());
  if (!match) return null;
  const language = match[1].toLowerCase();
  return LANGUAGES.includes(language) ? language : null;
}

// choice: "es" or "en" (a manual choice) or anything else for automatic. languages: the browser or desktop-app
// locale list in preference order. hint: the tag the server derived from its own process locale.
export function chooseLanguage({ choice, languages, hint } = {}) {
  if (LANGUAGES.includes(choice)) return choice;
  for (const tag of Array.isArray(languages) ? languages : []) {
    const found = normalizeTag(tag);
    if (found) return found;
  }
  return normalizeTag(hint) || "en";
}

export function translate(language, key, params) {
  const table = STRINGS[language] || STRINGS.en;
  let text = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : STRINGS.en[key];
  if (text === undefined) return key;
  if (params) text = text.replace(/\{([A-Za-z]+)\}/g, (whole, name) => (name in params ? String(params[name]) : whole));
  return text;
}
